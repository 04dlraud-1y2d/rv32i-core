#==============================================================
# test_rv32i.s — RV32I 전 명령어 동작 확인 프로그램
#
# 각 줄 끝의 주석이 "기대값"이다. 테스트벤치가 이 값을 검사한다.
# 직접 손으로 계산해 보고 주석과 맞춰보는 것이 좋은 연습이다.
# 특히 -3 = 0xFFFFFFFD 라는 걸 잊으면 무부호 비교 결과가 이해 안 된다.
#==============================================================

    # ---------------- 기본 상수 ----------------
    addi  x1,  x0, 10          # x1  = 10
    addi  x2,  x0, -3          # x2  = -3 (0xFFFFFFFD)
    addi  x23, x0, 0x100       # x23 = 256  (데이터 베이스 주소)
    addi  x25, x0, -1          # x25 = -1 (0xFFFFFFFF)

    # ---------------- I타입 ALU ----------------
    andi  x3,  x1, 6           # 0xA & 0x6 = 2
    ori   x4,  x1, 5           # 0xA | 0x5 = 15
    xori  x5,  x1, 15          # 0xA ^ 0xF = 5
    slti  x6,  x2, 0           # -3 <s 0 = 1
    sltiu x7,  x2, 0           # 0xFFFFFFFD <u 0 = 0
    slli  x8,  x1, 2           # 10 << 2 = 40
    srli  x9,  x1, 1           # 10 >> 1 = 5
    srai  x10, x2, 1           # -3 >>> 1 = -2

    # ---------------- R타입 ALU ----------------
    add   x11, x1, x2          # 10 + (-3) = 7
    sub   x12, x1, x2          # 10 - (-3) = 13
    sll   x13, x1, x1          # 10 << 10 = 10240
    slt   x14, x2, x1          # -3 <s 10 = 1
    sltu  x15, x2, x1          # 0xFFFFFFFD <u 10 = 0
    xor   x16, x1, x2          # 0xFFFFFFF7 = -9
    srl   x17, x1, x0          # 시프트량 0 → 10
    sra   x18, x2, x0          # 시프트량 0 → -3
    or    x19, x1, x2          # 0xFFFFFFFF = -1
    and   x20, x1, x2          # 0x00000008 = 8

    # ---------------- U타입 ----------------
    lui   x21, 0x12345         # x21 = 0x12345000
    auipc x22, 0               # x22 = 이 명령의 PC

    # ---------------- 워드 store/load ----------------
    sw    x1,  0(x23)          # mem[0x100] = 10
    lw    x24, 0(x23)          # x24 = 10

    # ---------------- 바이트/하프워드 (부호확장 vs 0확장) ----------------
    sb    x25, 4(x23)          # mem[0x104] 바이트 = 0xFF
    lb    x26, 4(x23)          # 부호확장 → -1
    lbu   x27, 4(x23)          # 0확장    → 255
    sh    x25, 8(x23)          # mem[0x108] 하프 = 0xFFFF
    lh    x28, 8(x23)          # 부호확장 → -1
    lhu   x29, 8(x23)          # 0확장    → 65535

    # ---------------- 비정렬 오프셋 (lsu 시프트 경로) ----------------
    # x30/x31은 뒤에서 덮어쓰므로 여기서는 임시 레지스터로 쓴다.
    addi  x30, x0, 0x5A
    sb    x30, 17(x23)         # 0x111 → 워드 0x110의 byte1 위치
    lbu   x31, 17(x23)         # = 0x5A
    sw    x31, 528(x0)         # mem[0x210] = 0x5A

    addi  x30, x0, 0x7AB
    sh    x30, 22(x23)         # 0x116 → 워드 0x114의 상위 하프워드
    lhu   x31, 22(x23)         # = 0x7AB
    sw    x31, 532(x0)         # mem[0x214] = 0x7AB

    # ---------------- 분기 6종 ----------------
    # 성립해야 하는 분기가 안 되면 +100이 섞여 들어가 바로 티가 난다.
    addi  x30, x0, 0
    beq   x0, x0, B1           # 성립 (0 == 0)
    addi  x30, x30, 100        #   ← 건너뛰어야 함
B1: addi  x30, x30, 1
    bne   x0, x0, B2           # 불성립
    addi  x30, x30, 2          #   ← 실행되어야 함
B2: blt   x2, x1, B3           # -3 <s 10 성립
    addi  x30, x30, 100
B3: addi  x30, x30, 4
    bge   x1, x2, B4           # 10 >=s -3 성립
    addi  x30, x30, 100
B4: addi  x30, x30, 8
    bltu  x1, x2, B5           # 10 <u 0xFFFFFFFD 성립
    addi  x30, x30, 100
B5: addi  x30, x30, 16
    bgeu  x2, x1, B6           # 0xFFFFFFFD >=u 10 성립
    addi  x30, x30, 100
B6: addi  x30, x30, 32
                               # x30 = 1+2+4+8+16+32 = 63

    # ---------------- JAL / JALR ----------------
    jal   x31, FUNC            # x31 = 복귀주소(= 다음 명령 주소)
    j     DONE                 # FUNC에서 복귀하면 여기로 → DONE
    addi  x30, x30, 100        #   ← 절대 도달하면 안 됨

FUNC:
    sw    x1, 512(x0)          # mem[0x200] = 10  (FUNC 실행 표식)
    jalr  x0, 0(x31)           # 복귀

DONE:
    ecall                      # halt → 시뮬레이션 종료
